"""Evaluation report: charts and tables from saved benchmark runs.

    python -m eval.report                     # latest real-model runs in eval/results
    python -m eval.report --include-standins  # also accept offline stand-in runs (labelled)

Reads the JSON files written by eval.run_retrieval and eval.run_answers, picks the
most complete, most recent run for each (benchmark, dataset), and writes
docs/evaluation/README.md plus SVG charts next to it. Nothing is measured here:
every number comes from a saved run, and the report names the file it came from.

By default runs made with offline stand-ins (hashing embedder, extractive LLM,
lexical entailment) are ignored, because their numbers say nothing about quality.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from eval import charts
from eval.run_retrieval import DEFAULT_OUT, ROOT

DEFAULT_REPORT = ROOT / "docs" / "evaluation"
DATASET_NAMES = {"teratai": "development", "teratai-heldout": "held-out"}
MODE_ORDER = ["bm25", "dense", "hybrid", "dense+rerank", "hybrid+rerank"]
CATEGORIES = ["lexical", "paraphrase", "malay"]


# ------------------------------------------------------------------ loading
def kind(result: dict[str, Any]) -> str | None:
    if isinstance(result.get("results"), dict) and "summary" in result["results"]:
        return "retrieval"
    if "rows" in result and "gate" in result:
        return "answers"
    return None  # e.g. a fusion sweep


def is_standin(result: dict[str, Any]) -> bool:
    env = result.get("environment", {})
    if env.get("embedding", {}).get("backend") == "hashing":
        return True
    if (env.get("reranker") or {}).get("backend") == "hashing":
        return True
    if kind(result) == "answers":
        if env.get("llm", {}).get("backend") != "ollama":
            return True
        if (result.get("entailment") or {}).get("backend") == "lexical":
            return True
    return False


def load_runs(results_dir: Path, include_standins: bool) -> list[dict[str, Any]]:
    runs = []
    for path in sorted(results_dir.glob("*.json")):
        try:
            result = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        k = kind(result)
        if k is None or (is_standin(result) and not include_standins):
            continue
        result["_file"] = path.name
        result["_kind"] = k
        result["_standin"] = is_standin(result)
        result.setdefault("dataset", "teratai")
        runs.append(result)
    return runs


def pick(runs: list[dict[str, Any]], k: str, dataset: str) -> dict[str, Any] | None:
    """The most complete run (most modes / questions), newest first among equals."""
    candidates = [r for r in runs if r["_kind"] == k and r["dataset"] == dataset]
    if not candidates:
        return None

    def completeness(r):
        if k == "retrieval":
            size = len(r["results"]["summary"])
        else:
            size = r["summary"]["overall"]["questions"] + (100 if r.get("entailment_table") else 0)
        return (size, r["timestamp"])

    return max(candidates, key=completeness)


# ------------------------------------------------------------------ helpers
def _pct(v: Any) -> str:
    return "—" if v is None else f"{v:.3f}"


def _label(dataset: str) -> str:
    return DATASET_NAMES.get(dataset, dataset)


def _provenance(r: dict[str, Any]) -> str:
    env = r["environment"]
    models = [env["embedding"].get("model")]
    if env.get("reranker"):
        models.append(env["reranker"].get("model"))
    if r["_kind"] == "answers":
        models.append(env.get("llm", {}).get("model"))
        if r.get("entailment"):
            models.append(r["entailment"].get("model"))
    tag = " **(offline stand-in, not a quality result)**" if r["_standin"] else ""
    return (
        f"| {r['_kind']} | {_label(r['dataset'])} | `{r['_file']}` | {r['timestamp']} | "
        f"`{r['dataset_hash']}` | {', '.join(f'`{m}`' for m in models if m)} | "
        f"{env.get('platform', '—')} | `{env.get('git_commit', '—')}`{tag} |"
    )


# ------------------------------------------------------------------ report
def build(runs: list[dict[str, Any]], threshold: float | None) -> tuple[str, dict[str, str]]:
    ret = {d: pick(runs, "retrieval", d) for d in DATASET_NAMES}
    ans = {d: pick(runs, "answers", d) for d in DATASET_NAMES}
    used = [r for r in [*ret.values(), *ans.values()] if r]
    svgs: dict[str, str] = {}
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python -m eval.report` from saved benchmark runs. Every number below",
        "comes from one of the files listed under *Runs*; nothing is typed in by hand.",
        "",
        "- **Development set** (`eval/datasets/teratai`): the questions used to choose",
        "  settings in Phases 3–7 (fusion weights, reranker depth, score gate, entailment",
        "  threshold). Results on it are optimistic by construction.",
        "- **Held-out set** (`eval/datasets/teratai-heldout`): 48 new questions over the",
        "  same documents, written in Phase 7 before any held-out run and not used to tune",
        "  anything. It is the honest estimate.",
        "",
    ]
    if any(r["_standin"] for r in used):
        lines += [
            "> **Warning:** some runs below use offline stand-ins (hashing embeddings,",
            "> extractive LLM, lexical entailment). Their numbers check the plumbing and",
            "> say nothing about quality.",
            "",
        ]
    if not used:
        lines += [
            "No benchmark runs found. Run the benchmarks first (see *Regenerating*).",
            "",
        ]

    # -------------------------------------------------------------- retrieval
    if any(ret.values()):
        modes = [
            m for m in MODE_ORDER if any(r and m in r["results"]["summary"] for r in ret.values())
        ]
        series = {
            f"{_label(d)} ({r['results']['scored_queries']} q)": [
                r["results"]["summary"].get(m, {}).get("overall", {}).get("mrr") for m in modes
            ]
            for d, r in ret.items()
            if r
        }
        svgs["retrieval-mrr.svg"] = charts.bar_chart(
            "Retrieval: MRR by search mode",
            modes,
            series,
            subtitle="Mean reciprocal rank of the first relevant section (higher is better)",
            y_label="MRR",
            pct=False,
        )
        lines += [
            "## Retrieval",
            "",
            "![Retrieval MRR by mode](retrieval-mrr.svg)",
            "",
            "| Dataset | Mode | Recall@1 | Recall@5 | Recall@10 | MRR | nDCG@10 | p50 ms |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for d, r in ret.items():
            if not r:
                continue
            for m in modes:
                o = r["results"]["summary"].get(m, {}).get("overall")
                if o:
                    lines.append(
                        f"| {_label(d)} | {m} | {_pct(o['recall@1'])} | {_pct(o['recall@5'])} | "
                        f"{_pct(o['recall@10'])} | {_pct(o['mrr'])} | {_pct(o['ndcg@10'])} | "
                        f"{o['latency_p50_ms']:.1f} |"
                    )
        focus = ret.get("teratai-heldout") or ret.get("teratai")
        assert focus is not None
        cats = [
            c
            for c in CATEGORIES
            if any(c in s.get("by_category", {}) for s in focus["results"]["summary"].values())
        ]
        focus_modes = [m for m in modes if m in focus["results"]["summary"]]
        svgs["retrieval-categories.svg"] = charts.bar_chart(
            f"Retrieval MRR by question type ({_label(focus['dataset'])} set)",
            cats,
            {
                m: [
                    focus["results"]["summary"][m].get("by_category", {}).get(c, {}).get("mrr")
                    for c in cats
                ]
                for m in focus_modes
            },
            subtitle="Keyword queries favour BM25; paraphrases and Malay need dense retrieval",
            y_label="MRR",
            pct=False,
        )
        lines += ["", "![Retrieval MRR by question type](retrieval-categories.svg)", ""]

    # ---------------------------------------------------------------- answers
    if any(ans.values()):
        metric_names = [
            ("Answer rate", "answer_rate"),
            ("Fact recall", "fact_recall"),
            ("Citation precision", "citation_precision"),
            ("Correct refusals", "correct_refusal_rate"),
        ]
        present = [d for d, r in ans.items() if r]
        flagged = all((ans[d] or {}).get("entailment") for d in present)
        svgs["answers.svg"] = charts.bar_chart(
            "Grounded answers: " + " vs ".join(f"{_label(d)} set" for d in present),
            [n for n, _ in metric_names],
            {
                f"{_label(d)} ({r['summary']['overall']['questions']} q)": [
                    r["summary"]["overall"].get(key) for _, key in metric_names
                ]
                for d, r in ans.items()
                if r
            },
            subtitle="Score gate off"
            + ("; entailment check scored but nothing removed" if flagged else ""),
        )
        lines += [
            "## Grounded answers",
            "",
            "![Answer metrics](answers.svg)",
            "",
            "| Dataset | Questions | Answer rate | Fact recall | Citation precision "
            "| Correct refusals | Unsupported sentences | p50 s | p95 s |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for d, r in ans.items():
            if not r:
                continue
            o = r["summary"]["overall"]
            lines.append(
                f"| {_label(d)} | {o['questions']} | {_pct(o['answer_rate'])} | "
                f"{_pct(o['fact_recall'])} | {_pct(o['citation_precision'])} | "
                f"{_pct(o['correct_refusal_rate'])} | {_pct(o['unsupported_sentence_rate'])} | "
                f"{(o['latency_p50_ms'] or 0) / 1000:.1f} | "
                f"{(o['latency_p95_ms'] or 0) / 1000:.1f} |"
            )
        lines += [
            "",
            "Fact recall counts an expected fact as found when one of its accepted wordings",
            "appears in the answer; it does not judge whether the rest of the answer is right.",
            "Cost is $0 for every run: all models run locally.",
            "",
        ]
        for d, r in ans.items():
            if not r or not r.get("entailment_table"):
                continue
            table = r["entailment_table"]
            name = f"entailment-{_label(d)}.svg"
            svgs[name] = charts.line_chart(
                f"Entailment threshold trade-off ({_label(d)} set)",
                [t["threshold"] for t in table],
                {
                    "Answer rate": [t["answer_rate"] for t in table],
                    "Fact recall": [t["fact_recall"] for t in table],
                    "Correct refusals": [t["correct_refusal_rate"] for t in table],
                    "Sentences removed": [t["sentences_removed"] for t in table],
                },
                subtitle=f"Removing sentences with P(entailment) below the threshold · "
                f"{(r.get('entailment') or {}).get('model', '')}",
                x_label="EKA_ANSWER_ENTAILMENT_THRESHOLD",
                marker_x=threshold,
                marker_label=f"configured {threshold:g}" if threshold is not None else "",
            )
            lines += [
                f"### Entailment threshold ({_label(d)} set)",
                "",
                f"![Entailment trade-off]({name})",
                "",
                "| Threshold | Answer rate | Fact recall | Correct refusals | Sentences removed |",
                "|---|---|---|---|---|",
            ]
            for t in table:
                lines.append(
                    f"| {t['threshold']} | {_pct(t['answer_rate'])} | {_pct(t['fact_recall'])} | "
                    f"{_pct(t['correct_refusal_rate'])} | {_pct(t['sentences_removed'])} |"
                )
            lines.append("")
        injection = [i for r in ans.values() if r for i in (r.get("injection") or [])]
        if injection:
            resisted = sum(i["resisted"] for i in injection)
            lines += [
                "### Prompt injection",
                "",
                f"{resisted} of {len(injection)} planted-instruction attacks resisted "
                "(payload absent from the answer). Four attacks is a smoke test, not a "
                "security guarantee.",
                "",
            ]

    # ----------------------------------------------------------------- runs
    if used:
        lines += [
            "## Runs",
            "",
            "| Benchmark | Dataset | File (eval/results) | Time (UTC) | Dataset hash | Models "
            "| Machine | Commit |",
            "|---|---|---|---|---|---|---|---|",
            *(_provenance(r) for r in used),
            "",
        ]
    lines += [
        "## Limitations",
        "",
        "- One author wrote the documents and both question sets, so the phrasing may be",
        "  easier than real users'. The held-out set guards against tuning to specific",
        "  questions, not against that bias.",
        "- The corpus is small (11 documents, 67 sections). One question moves a rate by",
        "  2–4 points, so differences of a few points are noise.",
        "- Fact recall is string matching against accepted wordings; an answer can match",
        "  and still contain an extra wrong claim, or be right in words the list misses.",
        "",
        "## Regenerating",
        "",
        "```bash",
        "python -m eval.run_retrieval                                   # development set",
        "python -m eval.run_retrieval --dataset eval/datasets/teratai-heldout",
        "python -m eval.run_answers                                     # needs Ollama",
        "python -m eval.run_answers --dataset eval/datasets/teratai-heldout --no-injection",
        "python -m eval.report",
        "```",
        "",
    ]
    return "\n".join(lines), svgs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--results", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--out", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--include-standins", action="store_true")
    parser.add_argument(
        "--threshold",
        type=float,
        help="Entailment threshold to mark on the chart (default: EKA_ANSWER_ENTAILMENT_THRESHOLD)",
    )
    args = parser.parse_args(argv)
    threshold = args.threshold
    if threshold is None:
        from app.core.config import Settings

        threshold = Settings().answer_entailment_threshold
    runs = load_runs(args.results, args.include_standins)
    report, svgs = build(runs, threshold)
    args.out.mkdir(parents=True, exist_ok=True)
    for name, svg in svgs.items():
        (args.out / name).write_text(svg)
    (args.out / "README.md").write_text(report)
    print(f"Wrote {args.out / 'README.md'} and {len(svgs)} chart(s) from {len(runs)} run(s).")
    if not runs:
        print("No usable runs: run the benchmarks first.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
