#!/usr/bin/env bash
# Pin the Docker image's Python dependencies: the app + the ML extra, no dev tools,
# at exactly the versions in requirements-ml.lock (what the tests ran with).
#
# PyTorch is left out on purpose: the image installs the CPU build of the same
# version from download.pytorch.org (a container on a Mac has no GPU to use), which
# avoids ~3 GB of NVIDIA CUDA libraries that PyPI's Linux torch wheels pull in.
set -euo pipefail
cd "$(dirname "$0")/.."

uv pip compile pyproject.toml --extra ml --universal --python-version 3.11 \
  -c requirements-ml.lock -q -o requirements-docker.lock.tmp
{
  echo "# Generated by scripts/lock-docker.sh: runtime + ML, pinned to requirements-ml.lock."
  echo "# torch, triton and the NVIDIA/CUDA packages are omitted; the Dockerfile installs"
  echo "# torch==$(awk -F'==' '/^torch==/{print $2}' requirements-ml.lock) (CPU build) from https://download.pytorch.org/whl/cpu."
  grep -vE '^(torch|triton|nvidia-[a-z0-9-]+|cuda-[a-z-]+)==' requirements-docker.lock.tmp
} > requirements-docker.lock
rm requirements-docker.lock.tmp
echo "Wrote requirements-docker.lock"
